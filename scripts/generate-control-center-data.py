def build_servers() -> list[dict[str, Any]]:
    """ui/control-center/sample-fleet.json - fleet telemetry has no v1
    contract fixture yet (see that file's _provenance note)."""
    sample = load_json(SAMPLE_FLEET_PATH)
    servers = sorted(sample["servers"], key=lambda s: s["id"])
    return servers


def build_hermes_tree() -> dict[str, Any]:
    """contracts/.../fixtures/hermes-orchestration-tree/valid-01.json.

    The fixture is a flat list of nodes with parent_subagent_id; this
    nests them into the {id, name, role, children} shape the UI expects.
    """
    fixture = load_fixture("hermes-orchestration-tree")
    nodes_by_id = {n["subagent_id"]: n for n in fixture["nodes"]}

    def to_ui_node(node: dict[str, Any]) -> dict[str, Any]:
        children = [to_ui_node(nodes_by_id[cid]) for cid in node.get("children", []) if cid in nodes_by_id]
        return {
            "id": node["subagent_id"],
            "name": node["role"].replace("_", " ").title(),
            "role": node.get("summary") or node.get("goal", ""),
            "state": node.get("state", ""),
            "active_tool": node.get("active_tool"),
            "children": children,
        }

    root = nodes_by_id.get(fixture.get("root_subagent_id"))
    tree = [to_ui_node(root)] if root else []
    return {
        "tree": tree,
        "session_id": fixture.get("session_id"),
        "generated_at": fixture.get("generated_at"),
        "active_count": fixture.get("active_count", 0),
        "completed_count": fixture.get("completed_count", 0),
        "failed_count": fixture.get("failed_count", 0),
    }


def build_hermes_events(tree_fixture_nodes: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """contracts/.../fixtures/hermes-orchestration-event/valid-01.json plus
    the state of every node in the hermes-orchestration-tree fixture -
    each node contributes one deterministic timeline entry so the "Jejak
    eksekusi" list has more than a single row."""
    events: list[dict[str, Any]] = []
    state_to_kind = {"RUNNING": "tool", "SUCCEEDED": "ok", "FAILED": "deny", "PENDING": "wait"}
    for node in tree_fixture_nodes:
        events.append({
            "a": node["subagent_id"],
            "k": state_to_kind.get(node.get("state", ""), "plan"),
            "m": node.get("summary") or node.get("goal", ""),
            "t": node.get("started_at", ""),
        })
    event_fixture = load_fixture("hermes-orchestration-event")
    events.append({
        "a": event_fixture["subagent_id"],
        "k": "tool",
        "m": event_fixture.get("summary", ""),
        "t": event_fixture.get("timestamp", ""),
    })
    events.sort(key=lambda e: e["t"])
    return events


def build_deployments() -> list[dict[str, Any]]:
    """Pairs contracts/.../deployment.request/valid-*.json (who/operation)
    with contracts/.../deployment-view/valid-*.json (state) on their real
    shared key: (target.server_id, target.deployment_id).

    The two fixture families are independently authored and, at present,
    describe entirely different deployments (deployment.request targets
    srv-0001/dep-0001; deployment-view targets server-acme-01/
    deployment-acme-hermes-01) - there is no genuine causal link between
    them. Pairing by sorted-filename index position would therefore
    fabricate actor -> deployment causality (e.g. attributing operator-1's
    restore request to an unrelated rollback view). Instead, only requests
    that share both server_id and deployment_id with a view are attributed
    to it; when no request matches, "who" is the neutral placeholder "-"
    rather than an invented or overly generic actor."""
    requests = load_fixtures("deployment.request")
    views = load_fixtures("deployment-view")
    requests_by_target = {
        (req["target"]["server_id"], req["target"]["deployment_id"]): req
        for req in requests
    }
    rows = []
    for view in views:
        target_key = (view["target"]["server_id"], view["target"]["deployment_id"])
        req = requests_by_target.get(target_key)
        desired = view["desired_state"]
        observed = view["observed_state"]
        in_sync = desired.get("status") == observed.get("status") and desired.get("version") == observed.get("version")
        state = "ok" if in_sync else ("rollback" if view.get("error_evidence") else "run")
        rows.append({
            "id": view["target"]["deployment_id"],
            "mod": "version " + str(desired.get("version")),
            "env": view.get("tenant_id", ""),
            "hosts": view["target"]["server_id"],
            "who": (req["actor"]["type"] + ":" + req["actor"]["id"]) if req else "-",
            "when": view.get("last_reconciled_at", ""),
            "state": state,
            "pct": 100 if in_sync else 60,
        })
    return rows


def build_jobs_and_operations() -> dict[str, Any]:
    """contracts/.../job-status.response/valid-01.json and
    contracts/.../operation-request/valid-01.json."""
    job = load_fixture("job-status.response")
    op = load_fixture("operation-request")
    jobs_running = [{
        "id": job["job_id"],
        "name": job["operation"] + " - " + job.get("target", {}).get("server_id", ""),
        "host": job.get("target", {}).get("server_id", ""),
        "pct": 100 if job.get("state") == "succeeded" else 50,
        "line": "state: " + job.get("state", ""),
    }]
    queue = [{
        "id": op["correlation_id"],
        "name": op["operation"] + " -> " + op["target"].get("server_id", ""),
        "by": op["actor"]["type"] + ":" + op["actor"]["id"],
        "risk": "high" if not op["permission"].get("granted", True) else "medium",
        "need": "Menunggu persetujuan" if op["permission"].get("requires_approval") else "Diizinkan otomatis",
        "age": "baru",
    }]
    return {"jobs_running": jobs_running, "queue": queue}


def build_health() -> list[dict[str, Any]]:
    """contracts/.../health-readiness.response/valid-01.json 'layers'."""
    fixture = load_fixture("health-readiness.response")
    rows = []
    for name, layer in sorted(fixture.get("layers", {}).items()):
        rows.append({
            "name": name.replace("_", " ").title(),
            "res": layer.get("status", ""),
            "detail": layer.get("proves", ""),
        })
    return rows


def build_backups() -> dict[str, Any]:
    """contracts/.../backup-status.response/valid-01.json."""
    fixture = load_fixture("backup-status.response")
    snapshot = {
        "id": fixture["backup_id"],
        "scope": fixture["target"]["server_id"],
        "size": str(round(fixture.get("size_bytes", 0) / (1024 * 1024), 1)) + " MB",
        "when": fixture.get("created_at", ""),
        "verify": "ok" if fixture.get("state") == "completed" else "fail",
        "dur": "-",
    }
    policy = [
        {"k": "Status", "v": fixture.get("state", "")},
        {"k": "Target", "v": fixture["target"]["server_id"]},
        {"k": "Manifest", "v": fixture.get("manifest_sha256", "")[:16] + "..."},
    ]
    return {"snapshots": [snapshot], "policy": policy}


