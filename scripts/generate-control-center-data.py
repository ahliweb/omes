"""scripts/generate-control-center-data.py - build ui/control-center/data.js
from the Control Center v1 contract fixtures (issue #211).

The Control Center UI prototype (ui/control-center/index.html) is a
reference-only, presentation prototype: the functional screens themselves
are tracked in #200/#201 and are NOT implemented yet. To keep the prototype
honest about where its example numbers come from, its domain data (fleet,
deployments, jobs/operations, health checks, backups, audit events,
workers, and the Hermes orchestration tree/events) is generated - not
hand-typed in the HTML - from:

  1. contracts/control-center/v1/fixtures/*/valid-*.json
     (the same fixtures scripts/check-contracts.py validates against their
     JSON Schemas), and
  2. ui/control-center/sample-fleet.json, a small, clearly-labelled
     supplementary sample file for fleet-level telemetry (CPU/memory/disk,
     OS, agent version, uptime) that has no v1 contract fixture yet.

A handful of sections (the Hermes integration "milestones"/"issues"
roadmap snapshot shown on the Progress screen) have no contract fixture at
all - they describe GitHub issue backlog state, not a runtime contract -
so they are kept as a small, clearly-labelled constant table in this
script (ROADMAP_MILESTONES / ROADMAP_ISSUES below), sourced from the
scratchpad's github.md screen map at authoring time. Update them by hand
when the backlog changes; everything else regenerates automatically.

Usage:
  scripts/generate-control-center-data.py            # write ui/control-center/data.js
  scripts/generate-control-center-data.py --check     # exit 1 if data.js is stale
  scripts/generate-control-center-data.py --out PATH  # write elsewhere (testing)

Output is deterministic: fixtures are read in sorted path order, JSON keys
are sorted, and no wall-clock timestamp is embedded, so two runs against
the same fixtures always produce byte-identical output.
"""
